#!/usr/bin/env python3
"""Build the offline documentation from docs/ and SUMMARY.md."""
from html import escape
import json
import os
from pathlib import Path
import re
import shutil
import unicodedata
from urllib.parse import urlsplit, urlunsplit

import mistune

ROOT = Path(__file__).resolve().parents[1]
DOCS = ROOT/'docs'
SITE = ROOT/'user_review'


def pages():
    group = 'Обзор'
    result = []
    for line in (DOCS/'SUMMARY.md').read_text().splitlines():
        if line.startswith('## '):group = line[3:]
        m = re.match(r'\s*\* \[([^]]+)\]\(([^)]+)\)', line)
        if m:result.append((group, m[1], m[2]))
    return result


def output_name(source):
    return 'index.html' if source == 'README.md' else str(Path(source).with_suffix('.html'))


def relative(target, page):
    return Path(os.path.relpath(target, Path(page).parent)).as_posix()


def slug(text):
    value = re.sub('<[^>]+>', '', text)
    value = unicodedata.normalize('NFKC', value).lower()
    return re.sub(r'[^\w-]+', '-', value).strip('-') or 'section'


def rewrite_links(body):
    def replace(m):
        url = urlsplit(m[2])
        if url.scheme or url.netloc or not url.path.endswith('.md'):return m[0]
        path = url.path[:-3]+'.html'
        if Path(path).name == 'README.html':path = str(Path(path).with_name('index.html'))
        return f'{m[1]}="{escape(urlunsplit((url.scheme,url.netloc,path,url.query,url.fragment)), quote=True)}"'
    return re.sub(r'(href|src)="([^"]+)"', replace, body)


def build():
    entries = pages()
    if len({x[2] for x in entries}) != len(entries):raise ValueError('Duplicate Markdown page in SUMMARY.md')
    markdown = mistune.create_markdown(escape=True, plugins=['table'])
    generated = []
    SITE.mkdir(exist_ok=True)
    manifest_path = SITE / 'site-manifest.json'
    previous = json.loads(manifest_path.read_text()).get('files', []) if manifest_path.exists() else []
    for index, (group, title, source) in enumerate(entries):
        source_path = DOCS/source
        if not source_path.resolve().is_relative_to(DOCS.resolve()):raise ValueError('Page escapes docs/')
        body = rewrite_links(markdown(source_path.read_text()))
        seen = set()
        def heading(m):
            name = base = slug(m[2]); suffix = 1
            while name in seen:suffix += 1; name = f'{base}-{suffix}'
            seen.add(name)
            return f'<h{m[1]} id="{name}">{m[2]}<a class="anchor" href="#{name}" aria-label="Ссылка на раздел">#</a></h{m[1]}>'
        body = re.sub(r'<h([1-6])>(.*?)</h\1>', heading, body)
        page = output_name(source)
        nav = []; current_group = None
        for nav_group, nav_title, nav_source in entries:
            if nav_group != current_group:
                if current_group is not None:nav.append('</ul>')
                nav.append(f'<p class="group">{escape(nav_group)}</p><ul>');current_group=nav_group
            current = ' aria-current="page"' if nav_source == source else ''
            nav.append(f'<li><a href="{relative(output_name(nav_source),page)}"{current}>{escape(nav_title)}</a></li>')
        nav.append('</ul>')
        adjacent = []
        for offset,label in [(-1,'← Предыдущая'),(1,'Следующая →')]:
            j=index+offset
            if 0 <= j < len(entries):
                _, other_title, other_source = entries[j]
                adjacent.append(f'<a href="{relative(output_name(other_source),page)}"><span>{label}</span>{escape(other_title)}</a>')
        text = f'''<!doctype html>
<!-- Generated by tools/build_docs.py; edit docs/{source}. -->
<html lang="ru"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1"><meta name="color-scheme" content="light"><title>{escape(title)} · GeoDataGen</title><link rel="stylesheet" href="{relative('assets/book.css',page)}"><script src="{relative('assets/book.js',page)}" defer></script></head>
<body><a class="skip" href="#content">Перейти к тексту</a><aside id="sidebar"><a class="brand" href="{relative('index.html',page)}">GeoDataGen</a><label class="sr-only" for="search">Найти страницу</label><input id="search" type="search" placeholder="Найти страницу…" autocomplete="off"><nav aria-label="Оглавление">{''.join(nav)}</nav><p class="empty" hidden>Страница не найдена</p><a class="repository" href="https://github.com/bySaf/geodatagen">Репозиторий GitHub ↗</a></aside>
<div class="body"><header><button id="menu" aria-expanded="false" aria-controls="sidebar" aria-label="Открыть оглавление">☰</button><span>{escape(group)} / {escape(title)}</span><a href="https://github.com/bySaf/geodatagen/blob/main/docs/{source}" aria-label="Исходник страницы">Markdown ↗</a></header><main id="content"><article>{body}</article><nav class="pagination" aria-label="Соседние страницы">{''.join(adjacent)}</nav><footer>GeoDataGen · документация проекта</footer></main></div></body></html>'''
        target = SITE/page; target.parent.mkdir(parents=True,exist_ok=True); target.write_text(text)
        generated.append(page)
    for source in sorted((DOCS/'assets').rglob('*')):
        if source.is_file():
            dest = SITE/'assets'/source.relative_to(DOCS/'assets');dest.parent.mkdir(parents=True,exist_ok=True);shutil.copyfile(source,dest)
            generated.append(dest.relative_to(SITE).as_posix())
    # Remove only files owned by our previous build. Unlisted local files and
    # experiment results are never considered stale documentation output.
    for entry in set(previous) - set(generated):
        stale = (SITE / entry).resolve()
        if stale.is_relative_to(SITE.resolve()) and stale.is_file():
            stale.unlink()
    manifest_path.write_text(json.dumps({'source':'docs/SUMMARY.md','files':generated},indent=2)+'\n')
    print(f'Documentation built: {len(entries)} pages, {len(generated)-len(entries)} assets')


if __name__ == '__main__':build()
